// Project outputs (spec 4.2, 4.3, 4.6): a plan, then apply it or compare it.
import * as fs from 'node:fs';
import * as path from 'node:path';
import { buildLock, LOCK_FILE, patchDrift, readLock, serializeLock } from './lock.ts';
import { parseFrontmatter } from './frontmatter.ts';
import { extractBlock, hasClaudeImport, renderBlock, upsertBlock, withClaudeImport, type PathFor } from './render.ts';
import type { FinalRule, Resolution, ResolvedPackage } from './resolve.ts';
import { headings } from './sections.ts';
import {
  ensureDir,
  exists,
  gitExcludeFile,
  isDir,
  isFile,
  isSymlink,
  linkIfChanged,
  readText,
  readTextIfExists,
  realpath,
  relPosix,
  writeIfChanged,
} from './util.ts';

export const STATE_DIR = path.join('node_modules', '.harnesspm');
const EXCLUDE_BEGIN = '# BEGIN harnesspm (generated by `harnesspm sync`; per-machine outputs)';
const EXCLUDE_END = '# END harnesspm';

export interface Plan {
  agentsMd: string;
  claudeMd: string;
  lock: string;
  /** Per-machine files under node_modules/.harnesspm: absolute path → content. */
  generated: Map<string, string>;
  /** Per-machine links: absolute link path → absolute target. */
  links: Map<string, string>;
  /** Paths for .git/info/exclude, relative to the project and starting with "/". */
  excludes: string[];
  warnings: string[];
}

function stableDir(pkg: ResolvedPackage): string {
  return path.join(STATE_DIR, 'pkgs', pkg.name);
}

function docsIndexText(dir: string, display: (file: string) => string): string {
  const lines = ['# Docs', ''];
  const walk = (current: string): void => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.name.endsWith('.md')) {
        const { data, body } = parseFrontmatter(readText(full), full);
        const first = headings(body.split('\n')).find((h) => h.level === 1);
        const title = first?.text ?? entry.name.slice(0, -3);
        const description = typeof data['description'] === 'string' ? `: ${data['description']}` : '';
        lines.push(`- [${title}](${display(full)})${description}`);
      }
    }
  };
  walk(dir);
  return `${lines.join('\n')}\n`;
}

export function computePlan(res: Resolution): Plan {
  const projectDir = res.projectDir;
  const warnings: string[] = [];
  const generated = new Map<string, string>();
  const links = new Map<string, string>();
  const excludes = new Set<string>([`/${STATE_DIR.split(path.sep).join('/')}/`]);
  const stateAbs = path.join(projectDir, STATE_DIR);

  // Stable package paths (spec 4.2).
  for (const pkg of res.packages) {
    if (pkg.layer !== 'project') links.set(path.join(projectDir, stableDir(pkg)), pkg.dir);
  }

  /** The project-relative path that outputs use for a file inside a package or the project. */
  const display = (file: string): string => {
    let best: ResolvedPackage | undefined;
    for (const pkg of res.packages) {
      if (pkg.layer === 'project') continue;
      if ((file === pkg.dir || file.startsWith(pkg.dir + path.sep)) && (!best || pkg.dir.length > best.dir.length)) best = pkg;
    }
    if (best) return relPosix(projectDir, path.join(projectDir, stableDir(best), path.relative(best.dir, file)));
    return relPosix(projectDir, file);
  };
  /** An absolute path that goes through the stable link, for link targets. */
  const stable = (file: string): string => path.join(projectDir, display(file));

  const generatedRule = (rule: FinalRule): string => path.join(stateAbs, 'rules', rule.pkg.plugin, `${rule.name}.md`);
  const paths: PathFor = {
    rule: (rule) => (rule.patches.length > 0 ? relPosix(projectDir, generatedRule(rule)) : display(rule.source)),
    docsIndex: (pkg) => {
      const docs = res.docs.find((d) => d.pkg === pkg);
      if (!docs) return undefined;
      const llms = path.join(docs.dir, 'llms.txt');
      if (isFile(llms)) return display(llms);
      const file = path.join(stateAbs, 'docs', pkg.plugin, 'llms.txt');
      generated.set(file, docsIndexText(docs.dir, display));
      return relPosix(projectDir, file);
    },
  };

  for (const rule of res.rules) {
    if (rule.patches.length > 0 && rule.activation !== 'always') generated.set(generatedRule(rule), rule.text);
  }

  // Skills: .claude/skills and .agents/skills. Write once when one folder links to the other.
  const skillRoots = [path.join(projectDir, '.claude', 'skills'), path.join(projectDir, '.agents', 'skills')];
  const realRoots = new Set<string>();
  const roots = skillRoots.filter((root) => {
    const real = isDir(root) ? realpath(root) : root;
    if (realRoots.has(real)) return false;
    realRoots.add(real);
    return true;
  });
  const addLink = (linkPath: string, target: string): void => {
    if (exists(linkPath) && !isSymlink(linkPath)) {
      warnings.push(`${relPosix(projectDir, linkPath)} exists and is not a harnesspm link; left as it is`);
      return;
    }
    links.set(linkPath, target);
    excludes.add(`/${relPosix(projectDir, linkPath)}`);
  };
  for (const skill of res.skills) {
    for (const root of roots) addLink(path.join(root, skill.name), stable(skill.dir));
  }

  // File-scoped rules also get a native Claude Code rule (spec 4.3, note 3).
  for (const rule of res.rules.filter((r) => r.activation === 'file')) {
    const target = rule.patches.length > 0 ? generatedRule(rule) : stable(rule.source);
    addLink(path.join(projectDir, '.claude', 'rules', 'harnesspm', rule.pkg.plugin, `${rule.name}.md`), target);
  }

  const block = renderBlock(res, paths);
  const agentsMd = upsertBlock(readTextIfExists(path.join(projectDir, 'AGENTS.md')), block);
  const claudeMd = withClaudeImport(readTextIfExists(path.join(projectDir, 'CLAUDE.md')));
  const previous = readLock(projectDir);
  const lock = buildLock(res, previous);
  warnings.push(...patchDrift(previous, lock));
  return { agentsMd, claudeMd, lock: serializeLock(lock), generated, links, excludes: [...excludes].sort(), warnings };
}

function readExcludeSection(text: string | undefined): string[] {
  if (text === undefined) return [];
  const start = text.indexOf(EXCLUDE_BEGIN);
  const end = text.indexOf(EXCLUDE_END, start);
  if (start < 0 || end < 0) return [];
  return text
    .slice(start + EXCLUDE_BEGIN.length, end)
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l.startsWith('/'));
}

function writeExcludeSection(text: string | undefined, entries: string[]): string {
  const section = `${EXCLUDE_BEGIN}\n${entries.join('\n')}\n${EXCLUDE_END}`;
  const current = text ?? '';
  const start = current.indexOf(EXCLUDE_BEGIN);
  const end = current.indexOf(EXCLUDE_END, start);
  if (start >= 0 && end >= 0) return current.slice(0, start) + section + current.slice(end + EXCLUDE_END.length);
  return `${current.replace(/\s*$/, '')}${current.trim() === '' ? '' : '\n\n'}${section}\n`;
}

/** Writes the plan. Returns the project-relative paths that changed. */
export function applyPlan(res: Resolution, plan: Plan): string[] {
  const projectDir = res.projectDir;
  const changed: string[] = [];
  const note = (file: string, did: boolean): void => {
    if (did) changed.push(relPosix(projectDir, file));
  };

  const stateAbs = path.join(projectDir, STATE_DIR);
  for (const sub of ['rules', 'docs']) fs.rmSync(path.join(stateAbs, sub), { recursive: true, force: true });
  for (const [file, content] of plan.generated) writeIfChanged(file, content);
  for (const [linkPath, target] of plan.links) note(linkPath, linkIfChanged(linkPath, target));

  const excludeFile = gitExcludeFile(projectDir);
  if (excludeFile) {
    const before = readTextIfExists(excludeFile);
    // Remove links from the last sync that this sync no longer writes.
    for (const entry of readExcludeSection(before)) {
      if (plan.excludes.includes(entry)) continue;
      const target = path.join(projectDir, entry);
      if (isSymlink(target)) {
        fs.unlinkSync(target);
        changed.push(entry.slice(1));
        // Remove folders that the link leaves empty, up to the project.
        for (let dir = path.dirname(target); dir.startsWith(projectDir + path.sep); dir = path.dirname(dir)) {
          try {
            fs.rmdirSync(dir);
          } catch {
            break;
          }
        }
      }
    }
    ensureDir(path.dirname(excludeFile));
    writeIfChanged(excludeFile, writeExcludeSection(before, plan.excludes));
  }

  note(path.join(projectDir, 'AGENTS.md'), writeIfChanged(path.join(projectDir, 'AGENTS.md'), plan.agentsMd));
  note(path.join(projectDir, 'CLAUDE.md'), writeIfChanged(path.join(projectDir, 'CLAUDE.md'), plan.claudeMd));
  note(path.join(projectDir, LOCK_FILE), writeIfChanged(path.join(projectDir, LOCK_FILE), plan.lock));
  return changed;
}

/** Compares the committed outputs with the plan (spec 6.4). Returns the differences. */
export function checkPlan(res: Resolution, plan: Plan): string[] {
  const projectDir = res.projectDir;
  const problems: string[] = [];
  const agents = readTextIfExists(path.join(projectDir, 'AGENTS.md'));
  if (extractBlock(agents) !== extractBlock(plan.agentsMd)) problems.push('AGENTS.md: the harnesspm block is out of date');
  if (!hasClaudeImport(readTextIfExists(path.join(projectDir, 'CLAUDE.md')))) problems.push('CLAUDE.md: the @AGENTS.md line is missing');
  if (readTextIfExists(path.join(projectDir, LOCK_FILE)) !== plan.lock) problems.push(`${LOCK_FILE} is out of date`);
  const lock = JSON.parse(plan.lock) as { packages: Record<string, { version: string; approved?: string }> };
  for (const [name, entry] of Object.entries(lock.packages)) {
    if (entry.approved !== undefined && entry.approved !== entry.version) {
      problems.push(`${name} ${entry.version} is pinned and not approved (approved: ${entry.approved}). Run \`npx harnesspm approve ${name}\`.`);
    }
  }
  return problems;
}
