/**
 * harnesspm's sections in the exclude file (spec 4.1). A project below the git root keys them by its path, such as
 * `harnesspm in docs-site/`, so that two projects in one repository never rewrite each other's entries.
 */
function sectionMarks(prefix: string): { team: Marks; added: Marks } {
  const name = prefix === '' ? 'harnesspm' : `harnesspm in ${prefix}`;
  return {
    team: [`# BEGIN ${name} (generated by \`harnesspm sync\`; per-machine outputs)`, `# END ${name}`],
    added: [`# BEGIN ${name}: added harnesses (generated by \`harnesspm sync\`; per-machine outputs)`, `# END ${name}: added harnesses`],
  };
}
const CODEX_MARKER = '# Generated by `harnesspm sync` for added harnesses. Do not edit.';

