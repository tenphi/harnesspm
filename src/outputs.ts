function repoSlug(projectDir: string): string {
  return `${path.basename(projectDir)}-${createHash('sha256').update(projectDir).digest('hex').slice(0, 8)}`;
}

function isTracked(projectDir: string, rel: string): boolean {
  return spawnSync('git', ['ls-files', '--error-unmatch', rel], { cwd: projectDir, encoding: 'utf8' }).status === 0;
}

export interface ClaudeImport {
  /** The folder of the AGENTS.md. */
  dir: string;
  file: string;
  /** The file's text after sync. Equal to the file on disk when nothing is missing. */
  text: string;
}

/**
 * The CLAUDE.md that makes Claude Code read the AGENTS.md in `dir` (spec 4.3, note 7): `CLAUDE.md` gets `@AGENTS.md`,
 * unless the folder's `.claude/CLAUDE.md` already imports `@../AGENTS.md`.
 */
export function claudeImport(dir: string): ClaudeImport {
  const file = path.join(dir, 'CLAUDE.md');
  const existing = readTextIfExists(file);
  const dotClaude = path.join(dir, '.claude', 'CLAUDE.md');
  const dotText = readTextIfExists(dotClaude);
  if (!hasClaudeImport(existing) && dotText !== undefined && hasClaudeImport(dotText, '@../AGENTS.md')) return { dir, file: dotClaude, text: dotText };
  return { dir, file, text: withClaudeImport(existing) };
}

/** Folders below the project with an AGENTS.md that git tracks, outside node_modules. */
function nestedAgentsDirs(projectDir: string): string[] {
  const result = spawnSync('git', ['ls-files', '-z', '--', ':(glob)**/AGENTS.md'], { cwd: projectDir, encoding: 'utf8' });
  if (result.status !== 0) return [];
  return result.stdout
    .split('\0')
    .filter((rel) => rel !== '' && rel !== 'AGENTS.md' && !rel.split('/').includes('node_modules'))
    .map((rel) => path.join(projectDir, path.dirname(rel)))
    .filter((dir) => isFile(path.join(dir, 'AGENTS.md')))
    .sort();
}

/**
 * The generated docs index (spec 2.7). A page with invalid frontmatter is listed without it, with a warning that names
 * the page by `label`. `display` gives the path the index links to, such as the page's copy.
 */
function docsIndexText(dir: string, display: (file: string) => string, warnings: string[], label = display): string {
  const lines = ['# Docs', ''];
  for (const page of docsPages(dir)) {
    const { data, body, error } = tryFrontmatter(readText(page), label(page));
    if (error !== undefined) {
      const warning = `${error}. The docs index lists the page by its heading or file name.`;
      if (!warnings.includes(warning)) warnings.push(warning);
    }
    const first = headings(body.split('\n')).find((h) => h.level === 1);
    const title = typeof data['title'] === 'string' ? data['title'] : (first?.text ?? path.basename(page).replace(/\.mdx?$/, ''));
    const description = typeof data['description'] === 'string' ? `: ${data['description']}` : '';
    lines.push(`- [${title}](${display(page)})${description}`);
  }
  return `${lines.join('\n')}\n`;
}

/** The pages of a docs folder (spec 2.7): `.md` and `.mdx` files, a linked one too, without the ones git ignores. */
function docsPages(dir: string): string[] {
  const pages: string[] = [];
  const keeps = gitKeeps(dir);
  const walk = (current: string): void => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (/\.mdx?$/.test(entry.name) && keeps(relPosix(dir, full))) pages.push(full);
    }
  };
  walk(dir);
  return pages;
}

const isRepoAdded = (pkg: ResolvedPackage): boolean => pkg.layer === 'added' && (pkg.scope === 'local' || pkg.entry === true);
export const isUserLevel = (pkg: ResolvedPackage): boolean => pkg.layer === 'added' && pkg.scope === 'user' && !pkg.entry;

/**
 * Paths that outputs show: stable package paths for dependencies, project-relative paths inside the
 * project, absolute paths elsewhere. Generated docs indexes are added to `generated`. `absolute` shows every path
 * in full, for user-level files: an agent reads them from any folder (spec 4.3, note 4).
 */
export function pathTools(res: Resolution, generatedRoot: (pkg: ResolvedPackage) => string, generated: Map<string, string>, warnings: string[], options: { absolute?: boolean } = {}) {
  const projectDir = res.projectDir;
  const show = (abs: string): string => (!options.absolute && abs.startsWith(projectDir + path.sep) ? relPosix(projectDir, abs) : abs);
  /** A dependency's file at its stable path under `node_modules/.harnesspm/pkgs/` (spec 4.3), or undefined for any other file. */
  const stablePath = (file: string): string | undefined => {
    let best: ResolvedPackage | undefined;
    for (const pkg of res.packages) {
      if (pkg.layer !== 'dependencies') continue;
      if ((file === pkg.dir || file.startsWith(pkg.dir + path.sep)) && (!best || pkg.dir.length > best.dir.length)) best = pkg;
    }
    return best ? path.join(projectDir, STATE_DIR, 'pkgs', best.name, path.relative(best.dir, file)) : undefined;
  };
  const display = (file: string): string => {
    const stable = stablePath(file);
    return stable !== undefined ? relPosix(projectDir, stable) : show(file);
  };
  const generatedRule = (rule: FinalRule): string => {
    const dir = path.join(generatedRoot(rule.pkg), 'rules', rule.pkg.plugin);
    return path.join(rule.variant ? path.join(dir, '.workspaces', hash(JSON.stringify([...rule.members].sort()))) : dir, `${rule.name}.md`);
  };
  /**
   * Where a dependency's docs are copied to, so that search tools find them (spec 4.3, note 8). Every dependency's,
   * a workspace package's too: the committed pointer then never depends on how a package manager installed it.
   */
  const docsCopy = (pkg: ResolvedPackage): string | undefined =>
    pkg.layer === 'dependencies' && res.docs.some((d) => d.pkg === pkg) ? path.join(projectDir, DOCS_DIR, pkg.plugin) : undefined;
  const paths: PathFor = {
    rule: (rule) => (rule.patches.length > 0 ? show(generatedRule(rule)) : display(rule.source)),
    docsIndex: (pkg) => {
      const docs = res.docs.find((d) => d.pkg === pkg);
      if (!docs) return undefined;
      const llms = path.join(docs.dir, 'llms.txt');
      const copy = docsCopy(pkg);
      if (copy !== undefined) {
        // A package's own llms.txt is copied with its pages. A generated one lists the copies.
        const index = path.join(copy, 'llms.txt');
        // A warning names the package's page, which its owner fixes, not the copy.
        if (!isFile(llms)) generated.set(index, docsIndexText(docs.dir, (file) => show(path.join(copy, path.relative(docs.dir, file))), warnings, display));
        return show(index);
      }
      if (isFile(llms)) return display(llms);
      const file = path.join(generatedRoot(pkg), 'docs', pkg.plugin, 'llms.txt');
      generated.set(file, docsIndexText(docs.dir, display, warnings));
      return show(file);
    },
  };
  return { show, display, stablePath, generatedRule, docsCopy, paths };
}

/**
 * The files of a docs copy, absolute path → text: the pages the index lists, and the package's own `llms.txt` (spec 4.3, note 8).
 * A link that leaves the docs folder, such as `../README.md`, would lead nowhere in the copy, so it points at the
 * file in the installed package instead. The page keeps that link for the package's own readers, such as its website.
 */
function docsCopyFiles(docsDir: string, copy: string, stablePath: (file: string) => string | undefined): Map<string, string> {
  const files = new Map<string, string>();
  const add = (source: string, rel: string): void => {
    const copied = path.join(copy, rel);
    const text = readText(source);
    let out = '';
    let last = 0;
    for (const { link, index } of relativeLinks(text)) {
      let target: string;
      try {
        target = path.resolve(path.dirname(path.join(docsDir, rel)), decodeURI(link));
      } catch {
        continue;
      }
      const stable = isInside(docsDir, target) || !fs.existsSync(target) ? undefined : stablePath(target);
      if (stable === undefined) continue;
      out += text.slice(last, index) + encodeURI(relPosix(path.dirname(copied), stable));
      last = index + link.length;
    }
    files.set(copied, out + text.slice(last));
  };
  for (const page of docsPages(docsDir)) add(page, path.relative(docsDir, page));
  const llms = path.join(docsDir, 'llms.txt');
  if (isFile(llms)) add(llms, 'llms.txt');
  return files;
}

/** The changes that added harnesses make to the repository's rules (spec 4.3, note 4). */
function changesSection(team: Resolution, full: Resolution, rulePath: (rule: FinalRule) => string): string | undefined {
  const added = new Set(full.packages.filter((p) => p.layer === 'added').map((p) => p.name));
  const lines: string[] = [];
  const texts: string[] = [];
  for (const { id, changed, members } of localRuleChanges(team, full)) {
    const where = team.workspaces.length > 0 && members.size !== team.workspaces.length + 1 ? ` in ${describeMembers(members)}` : '';
    if (!changed) {
      const by = full.excludedUnits.find((u) => u.id === id)?.by;
      if (by !== undefined && added.has(by)) lines.push(`- Ignore the rule ${id} in AGENTS.md${where}: ${by} turns it off on this machine.`);
      continue;
    }
    const by = [changed.replacedBy?.by, ...changed.patches.map((p) => p.by)].filter((b): b is string => b !== undefined && added.has(b));
    const who = [...new Set(by)].join(', ');
    if (changed.activation === 'always') texts.push(alwaysOnText(changed, `${id}, changed by ${who} on this machine; follow this text${where}`));
    else lines.push(`- Instead of the rule ${id} in AGENTS.md${where}, read ${rulePath(changed)} (changed by ${who})`);
  }
  if (lines.length === 0 && texts.length === 0) return undefined;
  return ["## Changes to this repository's rules", ...texts, ...(lines.length > 0 ? [lines.join('\n')] : [])].join('\n\n');
}

/**
 * A skill from an untrusted package without the SKILL.md keys that widen what the agent may do (spec 6.1): a generated
 * SKILL.md, with the rest of the skill's folder linked in. `author` is the package whose files the skill uses. Returns
 * the generated folder, `undefined` when the skill has none of those keys, or `null` when its frontmatter can't be read,
 * so the skill is left out.
 */
function narrowedSkill(
  skill: Resolution['skills'][number],
  author: ResolvedPackage,
  dir: string,
  stable: (file: string) => string,
  generated: Map<string, string>,
  links: Map<string, string>,
  warnings: string[],
): string | null | undefined {
  const file = path.join(skill.dir, 'SKILL.md');
  const parsed = tryFrontmatter(readTextIfExists(file) ?? '', file);
  if (parsed.error !== undefined) {
    warnings.push(`${skill.id}: left out, because its frontmatter can't be read (${parsed.error}) and ${author.name} is not trusted`);
    return null;
  }
  const widening = WIDENING_SKILL_KEYS.filter((key) => key in parsed.data);
  if (widening.length === 0) return undefined;
  for (const key of widening) warnings.push(`${skill.id}: "${key}" is left out, because ${author.name} is not trusted`);
  const data = Object.fromEntries(Object.entries(parsed.data).filter(([key]) => !widening.includes(key)));
  const keys = widening.map((key) => `"${key}"`).join(' and ');
  const note = `<!-- Generated by harnesspm from ${skill.id} without ${keys}, because ${author.name} is not trusted. -->`;
  generated.set(path.join(dir, 'SKILL.md'), withFrontmatter(data, `${note}\n\n${parsed.body.replace(/^\n+/, '')}`));
  for (const entry of listDir(skill.dir)) if (entry !== 'SKILL.md') links.set(path.join(dir, entry), stable(path.join(skill.dir, entry)));
  return dir;
}

/**
 * `team` is the dependency and project layers alone, for committed outputs. `full` adds the added
 * harnesses, for per-machine outputs. Without `team`, only the outputs of added harnesses change.
 */
export function computePlan(team: Resolution | undefined, full: Resolution, options: { widen?: boolean } = {}): Plan {
  const projectDir = full.projectDir;
  const warnings: string[] = [];
  const generated = new Map<string, string>();
  const links = new Map<string, string>();
  const teamExcludes = new Set<string>([`/${STATE_DIR.split(path.sep).join('/')}/`]);
  const addedExcludes = new Set<string>();
  const teamGen = path.join(projectDir, STATE_DIR);
  const addedGen = path.join(harnesspmHome(), 'generated', repoSlug(projectDir));
  const tools = pathTools(full, (pkg) => (pkg.layer === 'added' ? addedGen : teamGen), generated, warnings);

  if (team) for (const pkg of full.packages) if (pkg.layer === 'dependencies') links.set(path.join(projectDir, STATE_DIR, 'pkgs', pkg.name), pkg.dir);

  const stable = (file: string): string => path.resolve(projectDir, tools.display(file));
  const seenRoots = new Set<string>();
  const roots = [path.join(projectDir, '.claude', 'skills'), path.join(projectDir, '.agents', 'skills')].filter((root) => {
    const real = isDir(root) ? realpath(root) : root;
    if (seenRoots.has(real)) return false;
    seenRoots.add(real);
    return true;
  });
  const addLink = (linkPath: string, target: string, into: Set<string>): void => {
    if (exists(linkPath) && !isSymlink(linkPath)) {
      warnings.push(`${relPosix(projectDir, linkPath)} exists and is not a harnesspm link; left as it is`);
      return;
    }
    links.set(linkPath, target);
    into.add(`/${relPosix(projectDir, linkPath)}`);
  };

  const teamPatched = new Set(team?.rules.filter((rule) => rule.patches.length > 0).map(tools.generatedRule));
  // Generated rule files: patched rules that agents read from a file, with this machine's text.
  for (const rule of full.rules) {
    if (rule.activation === 'always' || isUserLevel(rule.pkg)) continue;
    if (rule.pkg.layer !== 'added' && !team) continue;
    const file = tools.generatedRule(rule);
    if (rule.patches.length > 0 || teamPatched.has(file)) generated.set(file, rule.text);
  }

  // File-scoped team rules also get a native Claude Code rule (spec 4.3, note 3).
  if (team) {
    for (const variants of rulesById(full.rules).values()) {
      const rule = variants[0]!;
      if (rule.activation !== 'file' || rule.pkg.layer === 'added') continue;
      // A repository-wide native rule cannot carry different text for different workspaces.
      if (variants.some((other) => other.text !== rule.text)) continue;
      const changed = rule.text !== readText(rule.original);
      const members = new Set(variants.flatMap((other) => [...other.members]));
      if (changed && full.workspaces.some((ws) => !members.has(ws.key))) continue;
      const target = changed ? tools.generatedRule(rule) : stable(rule.source);
      if (changed) generated.set(target, rule.text);
      addLink(path.join(projectDir, '.claude', 'rules', 'harnesspm', rule.pkg.plugin, `${rule.name}.md`), target, teamExcludes);
    }
  }

  let committed: Plan['committed'];
  const blockUnits = new Map<string, string[]>();
  const docsCopies = new Map<ResolvedPackage, string>();
  let rgignore: string | null | undefined;
  let lock: Lock | undefined = readLock(projectDir);
  let telemetryHeld: string | undefined;
  if (team) {
    const previous = lock;
    // A model run keeps the handler a person recorded, and may only remove it (spec 14.5).
    const wanted = team.config.telemetry?.send;
    const before = previous?.telemetry?.send;
    let record: Send | undefined = wanted;
    if (wanted !== undefined && options.widen === false && !sameSend(wanted, before)) {
      record = before;
      telemetryHeld = `telemetry handler: ${describeSend(wanted)}`;
    }
    lock = buildLock(team, previous, record);
    warnings.push(...patchDrift(previous, lock));
    const teamGenerated = new Map<string, string>();
    const teamLock = lock;
    const teamTools = pathTools(team, () => teamGen, teamGenerated, warnings);
    // Copies of the dependencies' docs, with an .rgignore that lets search tools into them (spec 4.3, note 8).
    for (const docs of team.docs) {
      const copy = teamTools.docsCopy(docs.pkg);
      if (copy === undefined) continue;
      for (const [file, text] of docsCopyFiles(docs.dir, copy, teamTools.stablePath)) teamGenerated.set(file, text);
      docsCopies.set(docs.pkg, copy);
    }
    const rgFile = path.join(projectDir, '.rgignore');
    const rgText = readTextIfExists(rgFile);
    const rgOurs = (): boolean => (rgText ?? RGIGNORE_MARKER).startsWith(RGIGNORE_MARKER) && !isTracked(projectDir, '.rgignore');
    if (docsCopies.size > 0) {
      teamExcludes.add(DOCS_EXCLUDE);
      // Formatters such as Prettier read .gitignore but not .git/info/exclude, so only a .gitignore keeps the copies out
      // of them. Git names a .gitignore by its path in the repository, and a global excludes file by its absolute path.
      const source = gitIgnoreSource(projectDir, DOCS_PROBE);
      if (source !== undefined && (source === null || path.isAbsolute(source) || path.basename(source) !== '.gitignore')) {
        warnings.push(`.gitignore does not ignore .harnesspm/, so formatters such as Prettier, which skip only what .gitignore lists, check the docs copies in .harnesspm/docs/. ${docsIgnoreAdvice(projectDir)}`);
      }
      if (rgOurs()) {
        rgignore = RGIGNORE;
        teamExcludes.add(RGIGNORE_EXCLUDE);
      } else if (!RGIGNORE_LINES.every((line) => rgText!.split('\n').includes(line))) {
        warnings.push(`.rgignore is not harnesspm's, so search tools skip the docs copies in .harnesspm/docs/. To let them in, add these lines to it, in this order: ${RGIGNORE_LINES.join(', ')}`);
      }
    } else if (rgText !== undefined && rgOurs()) rgignore = null;
    for (const rule of team.rules) {
      if (rule.activation !== 'always' && rule.patches.length > 0) teamGenerated.set(teamTools.generatedRule(rule), rule.text);
    }
    // One command form inside the project and outside it, where `-C` is the only difference (spec 4.6, 10.1).
    const prefix = (pkg: ResolvedPackage): string | undefined => (trustOf(pkg, team, teamLock).trusted ? NPX_ANY : undefined);
    // The root block holds what the root reaches and what every workspace shares (spec 3.6, 4.5).
    const keys = team.workspaces.map((ws) => ws.key);
    const shared = (pkg: ResolvedPackage): boolean => pkg.members.has('') || (keys.length > 0 && keys.every((k) => pkg.members.has(k)));
    const rootRules: FinalRule[] = [];
    const workspaceRules = new Map(keys.map((key) => [key, [] as FinalRule[]]));
    for (const variants of rulesById(team.rules).values()) {
      const first = variants[0]!;
      if (shared(first.pkg) && variants.every((rule) => rule.text === first.text)) rootRules.push(first);
      else for (const rule of variants) for (const key of rule.members) workspaceRules.get(key)?.push(rule);
    }
    const workspaces: NonNullable<Plan['committed']>['workspaces'] = [];
    const withBlocks: string[] = [];
    for (const ws of team.workspaces) {
      // Paths in a workspace's block are relative to its folder.
      const toWs = (p: string): string => (path.isAbsolute(p) ? p : relPosix(ws.dir, path.join(projectDir, p)));
      const wsPaths: PathFor = {
        rule: (rule) => toWs(teamTools.paths.rule(rule)),
        docsIndex: (pkg) => {
          const index = teamTools.paths.docsIndex(pkg);
          return index === undefined ? undefined : toWs(index);
        },
      };
      const rules = workspaceRules.get(ws.key)!;
      const includeOtherUnits = (pkg: ResolvedPackage): boolean => !shared(pkg) && pkg.members.has(ws.key);
      const units = renderSections(sectionsFor(team, team.packages, wsPaths, prefix, { compact: true, rules, includeOtherUnits }), wsPaths, { compact: true });
      const nested = keys.some((key) => key.startsWith(`${ws.key}/`));
      const content = units !== '' && nested
        ? `This block applies to this workspace. For files in a nested workspace, follow the harness rules for that workspace.\n\n${units}`
        : units;
      const agentsFile = path.join(ws.dir, 'AGENTS.md');
      const existing = readTextIfExists(agentsFile);
      const agentsMd = content !== '' ? upsertBlock(existing, wrapBlock(content, true)) : extractBlock(existing) !== undefined ? removeBlock(existing) : existing;
      workspaces.push({ dir: ws.dir, agentsMd });
      if (content === '') continue;
      withBlocks.push(ws.key);
      // Telemetry maps a load of this file to the always-on rules its block holds (spec 14.4).
      const always = rules.filter((r) => r.activation === 'always').map((r) => r.id);
      if (always.length > 0) blockUnits.set(path.join(realOrSame(ws.dir), 'AGENTS.md'), always);
    }
    const rootContent = [workspacesSection(withBlocks), renderSections(sectionsFor(team, team.packages, teamTools.paths, prefix, { compact: true, rules: rootRules, includeOtherUnits: shared }), teamTools.paths, { compact: true })]
      .filter((part) => part !== undefined && part !== '')
      .join('\n\n');
    const block = rootContent !== '' ? wrapBlock(rootContent, true) : wrapBlock('No harness units yet.');
    for (const [file, content] of teamGenerated) if (!generated.has(file)) generated.set(file, content);
    // The root CLAUDE.md silences every nested AGENTS.md in Claude Code, so each one gets its own import (spec 4.3, note 7).
    const claudeDirs = new Set([projectDir, ...workspaces.filter((ws) => ws.agentsMd !== undefined).map((ws) => ws.dir), ...nestedAgentsDirs(projectDir)]);
    committed = {
      agentsMd: upsertBlock(readTextIfExists(path.join(projectDir, 'AGENTS.md')), block),
      lock: serializeLock(lock),
      workspaces,
      claudeMds: [...claudeDirs].map(claudeImport),
    };
  }

  // Added harnesses with local scope, and every harness's entry for this repository (spec 4.3).
  let content = renderSections(sectionsFor(full, full.packages.filter(isRepoAdded), tools.paths, () => NPX_ANY), tools.paths);
  const changes = team ? changesSection(team, full, (rule) => tools.paths.rule(rule)) : undefined;
  if (changes !== undefined) content = content !== '' ? `${content}\n\n${changes}` : changes;

  const localFile = path.join(projectDir, 'CLAUDE.local.md');
  let localMd: string | undefined;
  if (content !== '' && isTracked(projectDir, 'CLAUDE.local.md')) {
    warnings.push('CLAUDE.local.md is tracked by git, so harnesspm does not write added harnesses into it');
    localMd = readTextIfExists(localFile);
  } else if (content !== '') {
    // CLAUDE.local.md counts as a CLAUDE.md: without one, Claude Code would stop reading AGENTS.md (spec 4.3, note 1).
    const needsImport = !isFile(path.join(projectDir, 'CLAUDE.md')) && isFile(path.join(projectDir, 'AGENTS.md'));
    localMd = upsertBlock(readTextIfExists(localFile), wrapBlock(content));
    if (needsImport && !hasClaudeImport(localMd)) localMd = `@AGENTS.md\n\n${localMd}`;
    addedExcludes.add('/CLAUDE.local.md');
  } else {
    // Remove only harnesspm's own block. A file without one stays as it is.
    const existing = readTextIfExists(localFile);
    localMd = extractBlock(existing) === undefined ? existing : removeBlock(existing, /^\s*(@AGENTS\.md)?\s*$/);
  }

  // Codex files are per machine unless the repository commits its own .codex/ (spec 4.3, note 2).
  const codexFile = path.join(projectDir, '.codex', 'config.toml');
  const codexTracked = ['.codex/config.toml', '.codex/hooks.json', '.codex/rules'].some((rel) => isTracked(projectDir, rel));
  const codexOurs = !codexTracked && (readTextIfExists(codexFile) ?? CODEX_MARKER).startsWith(CODEX_MARKER);
  if (!codexOurs) warnings.push('.codex/ belongs to the repository, so harnesspm writes nothing there and Codex misses some units. See `harnesspm status`.');
  const claudeOurs = !isTracked(projectDir, '.claude/settings.local.json');
  if (!claudeOurs) warnings.push('.claude/settings.local.json is tracked by git, so harnesspm writes no hooks or permissions there');

  // Executable units and sub-agents (spec 4.3, chapter 5), with trust (spec 6.2).
  const trust = (pkg: ResolvedPackage) => trustOf(pkg, full, lock);

  // Skills are linked as they are, except an untrusted package's skill that widens what the agent may do (spec 6.1).
  // A replaced skill's files come from the package that replaced it, so its trust decides.
  const skillsGen = path.join(teamGen, 'skills');
  for (const skill of full.skills) {
    if (isUserLevel(skill.pkg)) continue;
    const added = skill.pkg.layer === 'added';
    if (!added && !team) continue;
    let target = added ? skill.dir : stable(skill.dir);
    const author = skillAuthor(skill);
    if (author !== undefined && !trust(author).trusted) {
      const copy = narrowedSkill(skill, author, path.join(skillsGen, skill.pkg.plugin, skill.name), stable, generated, links, warnings);
      if (copy === null) continue;
      if (copy !== undefined) target = copy;
    }
    for (const root of roots) addLink(path.join(root, skill.name), target, added ? addedExcludes : teamExcludes);
  }

  const agentDirs ={ claudeAgents: path.join(projectDir, '.claude', 'agents'), codexAgents: path.join(projectDir, '.codex', 'agents') };
  // Hooks and MCP servers start the project's installed CLI file with node when it has one (spec 5.2).
  const teamRunner = runner(projectDir, NPX_ANY);
  const addedRunner = runner(projectDir, NPX_ANY);
  // Allow rules match the tool lines, `npx -y @harnesspm/cli run <unit>`, and until 1.0 the bare `npx harnesspm run <unit>` that some packages' text still types (spec 5.4).
  const teamExec = team ? desiredEntries(full, new Set(full.packages.filter((p) => p.layer !== 'added')), trust, { ...agentDirs, npx: () => [NPX_ANY, NPX_BARE], runner: () => teamRunner }) : undefined;
  const addedExec = desiredEntries(full, new Set(full.packages.filter(isRepoAdded)), trust, { ...agentDirs, npx: () => [NPX_ANY], runner: () => addedRunner });
  warnings.push(...(teamExec?.warnings ?? []), ...addedExec.warnings);

  // Telemetry's agent events (spec 14.4): harnesspm's own hooks, when the recorded handler and this machine allow them.
  let telemetryIndex: string | undefined;
  if (team && teamExec) {
    const state = telemetryState(projectDir, team.config.telemetry, lock?.telemetry?.send);
    const events = AGENT_EVENTS.filter((e) => state.events.has(e));
    if (events.length > 0) {
      teamExec.claude.hooks.push(...telemetryHooks(teamRunner.shell, 'claude', events));
      teamExec.codex.hooks.push(...telemetryHooks(teamRunner.shell, 'codex', events));
      const index = telemetryIndexFor(team, tools.generatedRule, (pkg) => path.join(teamGen, 'docs', pkg.plugin, 'llms.txt'), docsCopies, blockUnits);
      telemetryIndex = `${JSON.stringify(index, null, 2)}\n`;
    }
  }

  return {
    ...(committed ? { committed } : {}),
    generated,
    // teamGen/docs holds generated indexes, and the copies a version before 0.14 wrote there, which a sync removes.
    generatedRoots: [...(team ? [path.join(teamGen, 'rules'), path.join(teamGen, 'docs'), path.join(projectDir, DOCS_DIR), skillsGen] : []), addedGen],
    links,
    ...(rgignore !== undefined ? { rgignore } : {}),
    ...(team ? { teamExcludes: [...teamExcludes].sort() } : {}),
    addedExcludes: [...addedExcludes].sort(),
    localMd,
    codexInstructions: content,
    codexOurs,
    claudeOurs,
    exec: { ...(teamExec ? { team: teamExec } : {}), added: addedExec },
    ...(telemetryIndex !== undefined ? { telemetryIndex } : {}),
    ...(telemetryHeld !== undefined ? { telemetryHeld } : {}),
    warnings,
  };
}

/**
 * Claude Code: reads, skills, file-scoped rules and workspace blocks it loads by itself, sessions. Codex: sessions only
 * (spec 14.4). `prefix` is the runner, the installed CLI file when there is one, because npx costs about 0.4 s per call.
 */
function telemetryHooks(prefix: string, agent: 'claude' | 'codex', events: EventType[]): HookEntry[] {
  const command = `${prefix} track --agent ${agent}`;
  const hook = (event: string, matcher?: string): HookEntry => ({ event, ...(matcher !== undefined ? { matcher } : {}), command, timeout: 10, async: true });
  const hooks: HookEntry[] = [];
  if (agent === 'claude') {
    const tools = [...(events.includes('read') ? ['Read'] : []), ...(events.includes('skill') ? ['Skill'] : [])];
    if (tools.length > 0) hooks.push(hook('PostToolUse', tools.join('|')));
    // `nested_traversal` and `include`: a workspace's CLAUDE.md, and the AGENTS.md it imports (spec 4.5).
    if (events.includes('read')) hooks.push(hook('InstructionsLoaded', 'path_glob_match|nested_traversal|include'));
  }
  if (events.includes('session')) hooks.push(hook('SessionStart'));
  return hooks;
}

const realOrSame = (p: string): string => {
  try {
    return realpath(p);
  } catch {
    return p;
  }
};

/**
 * Maps the files and folders agents read to the units of the dependency and project layers (spec 14.4). `blocks` maps
 * each workspace's AGENTS.md to the always-on rules in its managed block.
 */
function telemetryIndexFor(
  res: Resolution,
  generatedRule: (rule: FinalRule) => string,
  generatedDocsIndex: (pkg: ResolvedPackage) => string,
  docsCopies: Map<ResolvedPackage, string>,
  blocks: Map<string, string[]>,
): TelemetryIndex {
  const team = (pkg: ResolvedPackage): boolean => pkg.layer !== 'added';
  const repository = remoteKey(res.projectDir);
  const index: TelemetryIndex = {
    project: res.projectName,
    // Empty when there is no remote, so no event asks git again.
    repository: repository ?? '',
    workspaces: res.workspaces.map((ws) => ws.key),
    packages: {},
    files: {},
    dirs: {},
    skills: {},
    blocks: Object.fromEntries(blocks),
  };
  for (const pkg of res.packages.filter(team)) index.packages[pkg.plugin] = { package: pkg.name, version: pkg.version };
  for (const rule of res.rules.filter((r) => team(r.pkg))) {
    for (const file of [rule.original, rule.source, generatedRule(rule)]) index.files[realOrSame(file)] = rule.id;
  }
  for (const docs of res.docs.filter((d) => team(d.pkg))) {
    index.dirs[realOrSame(docs.dir)] = docs.id;
    index.files[realOrSame(generatedDocsIndex(docs.pkg))] = docs.id;
    // The copy may not exist yet, so its real path comes from the project's.
    const copy = docsCopies.get(docs.pkg);
    if (copy !== undefined) index.dirs[path.join(realOrSame(res.projectDir), path.relative(res.projectDir, copy))] = docs.id;
  }
  for (const skill of res.skills.filter((s) => team(s.pkg))) {
    index.dirs[realOrSame(skill.dir)] = skill.id;
    index.skills[skill.name] = skill.id;
  }
  return index;
}

function sectionRange(lines: string[], marks: Marks): [number, number] | undefined {
  const start = lines.indexOf(marks[0]);
  if (start < 0) return undefined;
  const end = lines.indexOf(marks[1], start);
  return end < 0 ? undefined : [start, end];
}

/** A section's entries, as paths from the project folder such as `/CLAUDE.local.md`. Entries start at the git root, so `prefix` is cut off. */
function readSection(text: string | undefined, marks: Marks, prefix: string): string[] {
  const lines = (text ?? '').split('\n');
  const range = sectionRange(lines, marks);
  const anchor = excludeEntry(prefix, '');
  return range ? lines.slice(range[0] + 1, range[1]).filter((l) => l.startsWith(anchor)).map((l) => `/${l.slice(anchor.length)}`) : [];
}

/**
 * The sections of a project's entries. harnesspm 0.9 and earlier wrote a project below the git root into the root's
 * team section, from the project's folder, so its patterns missed its files. That section is `legacy` when the root does
 * not use harnesspm: no other project writes it then. Read from the project's folder, it lists the project's last entries.
 */
function projectSections(prefix: string, root: string): { marks: { team: Marks; added: Marks }; legacy?: Marks } {
  const marks = sectionMarks(prefix);
  return prefix !== '' && !isFile(path.join(root, CONFIG_FILE)) ? { marks, legacy: sectionMarks('').team } : { marks };
}

/** The per-machine paths that harnesspm's last sync listed in .git/info/exclude, from the project folder, such as `/CLAUDE.local.md`. */
export function excludedBySync(projectDir: string): string[] {
  const exclude = gitExclude(projectDir);
  if (!exclude) return [];
  const text = readTextIfExists(exclude.file);
  const { marks, legacy } = projectSections(exclude.prefix, exclude.root);
  return [...readSection(text, marks.team, exclude.prefix), ...readSection(text, marks.added, exclude.prefix), ...(legacy ? readSection(text, legacy, '') : [])];
}

/** Replaces a section with `entries`, paths from the project folder, anchored at the git root by `prefix`. No entries remove it. */
function writeSection(text: string | undefined, marks: Marks, entries: string[], prefix: string): string {
  const lines = (text ?? '').split('\n');
  const range = sectionRange(lines, marks);
  const section = entries.length > 0 ? [marks[0], ...entries.map((entry) => excludeEntry(prefix, entry)), marks[1]] : [];
  if (range) lines.splice(range[0], range[1] - range[0] + 1, ...section);
  else if (section.length > 0) {
    while (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
    if (lines.length > 0) lines.push('');
    lines.push(...section);
  }
  while (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
  return lines.length > 0 ? `${lines.join('\n')}\n` : '';
}

function unlinkAndPrune(target: string, stopAt: string): void {
  fs.unlinkSync(target);
  for (let dir = path.dirname(target); dir.startsWith(stopAt + path.sep); dir = path.dirname(dir)) {
    try {
      fs.rmdirSync(dir);
    } catch {
      break;
    }
  }
}

/**
 * The per-machine record of the entries harnesspm wrote for this project (spec 4.7): in the clone's git folder, or,
 * in a folder that is not a git repository, in ~/.harnesspm/state/, so sync never creates a `.git` folder there.
 * A project below the git root has its own, such as `harnesspm/docs-site/state.json`, so that two projects in one
 * repository never take each other's entries for their own.
 */
export function repoStateFile(projectDir: string): string {
  const result = spawnSync('git', ['rev-parse', '--show-prefix', '--git-path', 'harnesspm'], { cwd: projectDir, encoding: 'utf8' });
  if (result.status !== 0) return path.join(harnesspmHome(), 'state', `${repoSlug(projectDir)}.json`);
  const [prefix = '', p = ''] = result.stdout.split('\n');
  return path.join(path.isAbsolute(p) ? p : path.join(projectDir, p), ...prefix.split('/').filter(Boolean), 'state.json');
}

export function repoTargets(projectDir: string, plan: Pick<Plan, 'claudeOurs' | 'codexOurs'>): Targets {
  return {
    claudeSettings: path.join(projectDir, '.claude', 'settings.local.json'),
    claudeJson: claudeJsonFile(),
    claudeProject: projectDir,
    codexHooks: path.join(projectDir, '.codex', 'hooks.json'),
    codexRules: path.join(projectDir, '.codex', 'rules', 'harnesspm.rules'),
    stateFile: repoStateFile(projectDir),
    writeClaude: plan.claudeOurs,
    writeCodex: plan.codexOurs,
  };
}

export interface ApplyResult {
  changed: string[];
  /** Entries a model run could not add (spec 6.2, rule 4). */
  held: string[];
  /** True when some of them come from the repository's layers, not from added harnesses. */
  teamHeld: boolean;
}

/** Writes or removes the `.rgignore` that lets search tools into the docs copies (spec 4.3). */
export function writeRgignore(projectDir: string, plan: Plan): void {
  const file = path.join(projectDir, '.rgignore');
  if (plan.rgignore === null) fs.rmSync(file, { force: true });
  else if (plan.rgignore !== undefined) writeIfChanged(file, plan.rgignore);
}

/** Where the `/.harnesspm/` line goes: the .gitignore of the project folder, named when it is below the git root. */
export function docsIgnoreAdvice(projectDir: string): string {
  const prefix = gitExclude(projectDir)?.prefix ?? '';
  return `Add this line to ${prefix === '' ? '.gitignore' : `the .gitignore in ${prefix}`}: ${DOCS_EXCLUDE}`;
}

/** Adds `entries` to the project's section of .git/info/exclude and keeps the entries a sync wrote there. */
export function addExcludes(projectDir: string, entries: string[]): void {
  const exclude = gitExclude(projectDir);
  if (!exclude || entries.length === 0) return;
  const { marks } = projectSections(exclude.prefix, exclude.root);
  const before = readTextIfExists(exclude.file);
  const current = readSection(before, marks.team, exclude.prefix);
  if (entries.every((entry) => current.includes(entry))) return;
  writeIfChanged(exclude.file, writeSection(before, marks.team, [...new Set([...current, ...entries])].sort(), exclude.prefix));
}

/**
 * Writes the plan. Returns the project-relative paths that changed and the entries held back.
 * `committed: false` writes only the per-machine outputs, as a sync with `CI=true` does (spec 6.4).
 * `reviewed: true` lets a model run write the repository's entries, because they are as a person reviewed them (spec
 * 6.2, rule 4). Entries of added harnesses still wait for a person.
 */
export function applyPlan(projectDir: string, plan: Plan, options: { committed?: boolean; reviewed?: boolean } = {}): ApplyResult {
  const changed: string[] = [];
  const held: string[] = [];
  let teamHeld = false;
  const note = (file: string, did: boolean): void => {
    if (did) changed.push(relPosix(projectDir, file));
  };

  for (const root of plan.generatedRoots) fs.rmSync(root, { recursive: true, force: true });
  // The docs copies and the .rgignore wait for .git/info/exclude below, so that a sync that cannot write it leaves
  // nothing a commit would take.
  const docsRoot = path.join(projectDir, DOCS_DIR);
  const copies = [...plan.generated].filter(([file]) => isInside(docsRoot, file));
  for (const [file, content] of plan.generated) if (!isInside(docsRoot, file)) writeIfChanged(file, content);
  for (const [linkPath, target] of plan.links) note(linkPath, linkIfChanged(linkPath, target));

  // Executable entries in shared files, before the excludes so that every written file is listed.
  const person = caller() !== 'model';
  const targets = repoTargets(projectDir, plan);
  const teamExcludes = plan.teamExcludes ? [...plan.teamExcludes] : undefined;
  const addedExcludes = [...plan.addedExcludes];
  let codexMcp: Record<string, Record<string, unknown>> = {};
  for (const [group, entries, into] of [['team', plan.exec.team, teamExcludes], ['added', plan.exec.added, addedExcludes]] as const) {
    if (!entries) continue;
    const applied = applyEntries(group, entries, targets, person || (group === 'team' && options.reviewed === true));
    for (const file of applied.changed) changed.push(file.startsWith(projectDir + path.sep) ? relPosix(projectDir, file) : file);
    held.push(...applied.held);
    if (group === 'team' && applied.held.length > 0) teamHeld = true;
    codexMcp = applied.codexMcp;
    for (const file of applied.files) if (file.startsWith(projectDir + path.sep)) into?.push(`/${relPosix(projectDir, file)}`);
  }

  // .codex/config.toml: developer_instructions and MCP servers.
  const codexFile = path.join(projectDir, '.codex', 'config.toml');
  if (plan.codexOurs) {
    const parts = [
      ...(plan.codexInstructions !== '' ? [`developer_instructions = ${tomlString(plan.codexInstructions)}`] : []),
      ...(Object.keys(codexMcp).length > 0 ? [tomlTables('mcp_servers', codexMcp)] : []),
    ];
    if (parts.length > 0) {
      note(codexFile, writeIfChanged(codexFile, `${CODEX_MARKER}\n${parts.join('\n\n')}\n`));
      addedExcludes.push('/.codex/config.toml');
    } else if (isFile(codexFile)) {
      fs.rmSync(codexFile);
      changed.push('.codex/config.toml');
    }
  }
  for (const dir of [path.join(projectDir, '.codex', 'rules'), path.join(projectDir, '.codex', 'agents'), path.join(projectDir, '.codex'), path.join(projectDir, '.claude', 'agents')]) {
    try {
      fs.rmdirSync(dir);
    } catch {
      // Not empty, or not there.
    }
  }

  const exclude = gitExclude(projectDir);
  if (exclude) {
    const { prefix } = exclude;
    const { marks, legacy } = projectSections(prefix, exclude.root);
    const before = readTextIfExists(exclude.file);
    // harnesspm.local.json is never committed, also when a person writes it by hand for an opt-out (spec 14.6).
    if (isFile(path.join(projectDir, 'harnesspm.local.json')) && !(before ?? '').split('\n').includes(excludeEntry(prefix, 'harnesspm.local.json'))) addedExcludes.push('/harnesspm.local.json');
    const prevTeam = [...readSection(before, marks.team, prefix), ...(legacy ? readSection(before, legacy, '') : [])];
    const prevAdded = readSection(before, marks.added, prefix);
    const keep = new Set([...(teamExcludes ?? prevTeam), ...addedExcludes]);
    // Remove links from the last sync that this sync no longer writes.
    for (const entry of new Set([...prevTeam, ...prevAdded])) {
      const target = path.join(projectDir, entry);
      if (keep.has(entry) || !isSymlink(target)) continue;
      unlinkAndPrune(target, projectDir);
      changed.push(entry.slice(1));
    }
    let text = before;
    const sorted = (list: string[]): string[] => [...new Set(list)].sort();
    if (teamExcludes) {
      // The project's own section takes over the entries an older harnesspm wrote into the root's.
      if (legacy) text = writeSection(text, legacy, [], '');
      text = writeSection(text, marks.team, sorted(teamExcludes), prefix);
    }
    text = writeSection(text, marks.added, sorted(addedExcludes), prefix);
    writeIfChanged(exclude.file, text);
  }

  // Only where git ignores them, as fetch does: a .gitignore pattern can bring the folder back (spec 4.3, note 8).
  if (copies.length === 0 || gitKeepsOut(projectDir, DOCS_PROBE)) {
    for (const [file, content] of copies) writeIfChanged(file, content);
    writeRgignore(projectDir, plan);
  }

  if (plan.committed && options.committed !== false) {
    note(path.join(projectDir, 'AGENTS.md'), writeIfChanged(path.join(projectDir, 'AGENTS.md'), plan.committed.agentsMd));
    note(path.join(projectDir, LOCK_FILE), writeIfChanged(path.join(projectDir, LOCK_FILE), plan.committed.lock));
    for (const ws of plan.committed.workspaces) {
      const agentsFile = path.join(ws.dir, 'AGENTS.md');
      if (ws.agentsMd !== undefined) note(agentsFile, writeIfChanged(agentsFile, ws.agentsMd));
      else if (isFile(agentsFile)) {
        fs.rmSync(agentsFile);
        changed.push(relPosix(projectDir, agentsFile));
      }
    }
    for (const claude of plan.committed.claudeMds) note(claude.file, writeIfChanged(claude.file, claude.text));
  }

  // The index of harnesspm's agent hooks, only when the team layers were resolved.
  if (plan.committed) {
    const indexFile = path.join(projectDir, INDEX_FILE);
    if (plan.telemetryIndex !== undefined) writeIfChanged(indexFile, plan.telemetryIndex);
    else fs.rmSync(indexFile, { force: true });
  }

  const localFile = path.join(projectDir, 'CLAUDE.local.md');
  if (plan.localMd !== undefined) note(localFile, writeIfChanged(localFile, plan.localMd));
  else if (isFile(localFile)) {
    fs.rmSync(localFile);
    changed.push('CLAUDE.local.md');
  }
  return { changed, held, teamHeld };
}

/** Compares the committed outputs with the plan (spec 6.4). Returns the differences. */
export function checkPlan(projectDir: string, plan: Plan): string[] {
  if (!plan.committed) return ['the dependencies are not installed, so the committed outputs cannot be checked'];
  const problems: string[] = [];
  const agents = readTextIfExists(path.join(projectDir, 'AGENTS.md'));
  if (extractBlock(agents) !== extractBlock(plan.committed.agentsMd)) problems.push('AGENTS.md: the harnesspm block is out of date');
  if (!sameLock(readTextIfExists(path.join(projectDir, LOCK_FILE)), plan.committed.lock)) problems.push(`${LOCK_FILE} is out of date`);
  for (const ws of plan.committed.workspaces) {
    const rel = relPosix(projectDir, path.join(ws.dir, 'AGENTS.md'));
    if (extractBlock(readTextIfExists(path.join(ws.dir, 'AGENTS.md'))) !== extractBlock(ws.agentsMd)) problems.push(`${rel}: the harnesspm block is out of date`);
  }
  for (const claude of plan.committed.claudeMds) {
    if (readTextIfExists(claude.file) === claude.text) continue;
    const agents = relPosix(projectDir, path.join(claude.dir, 'AGENTS.md'));
    problems.push(`${relPosix(projectDir, claude.file)}: the @AGENTS.md line is missing, so Claude Code does not read ${agents}`);
  }
  const lock = JSON.parse(plan.committed.lock) as { packages: Record<string, { version?: string; approved?: string }> };
  for (const [name, entry] of Object.entries(lock.packages)) {
    if (entry.approved !== undefined && entry.approved !== entry.version) {
      problems.push(`${name} ${entry.version} is pinned and not approved (approved: ${entry.approved}). Run \`${NPX_ANY} approve ${name}\`.`);
    }
  }
  return problems;
}
