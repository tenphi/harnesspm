export const STATE_DIR = path.join('node_modules', '.harnesspm');
const TEAM_SECTION = ['# BEGIN harnesspm (generated by `harnesspm sync`; per-machine outputs)', '# END harnesspm'] as const;
const ADDED_SECTION = ['# BEGIN harnesspm: added harnesses (generated by `harnesspm sync`; per-machine outputs)', '# END harnesspm: added harnesses'] as const;
const CODEX_MARKER = '# Generated by `harnesspm sync` for added harnesses. Do not edit.';

export interface Plan {
  /** Committed outputs. Undefined when the team layers were not resolved. */
  committed?: {
    agentsMd: string;
    claudeMd: string;
    lock: string;
    /** A monorepo's workspace files (spec 4.5). Undefined `agentsMd` removes a file that held only the block. */
    workspaces: { dir: string; agentsMd: string | undefined; claudeMd: string | undefined }[];
  };
  /** Per-machine files: absolute path → content. */
  generated: Map<string, string>;
  /** Folders whose generated files this plan replaces. */
  generatedRoots: string[];
  /** Per-machine links: absolute link path → absolute target. */
  links: Map<string, string>;
  /** Entries for the team section of .git/info/exclude. Undefined leaves the section as it is. */
  teamExcludes?: string[];
  addedExcludes: string[];
  /** New CLAUDE.local.md, or undefined to remove harnesspm's block from it. */
  localMd: string | undefined;
  /** Text for Codex's developer_instructions. Empty when there is none. */
  codexInstructions: string;
  /** False when .codex/ belongs to the repository. */
  codexOurs: boolean;
  /** False when the repository tracks .claude/settings.local.json. */
  claudeOurs: boolean;
  /** Executable entries per group. The team group is missing when the team layers were not resolved. */
  exec: { team?: ExecEntries; added: ExecEntries };
  warnings: string[];
}

function repoSlug(projectDir: string): string {
  return `${path.basename(projectDir)}-${createHash('sha256').update(projectDir).digest('hex').slice(0, 8)}`;
}

function isTracked(projectDir: string, rel: string): boolean {
  return spawnSync('git', ['ls-files', '--error-unmatch', rel], { cwd: projectDir, encoding: 'utf8' }).status === 0;
}

function docsIndexText(dir: string, display: (file: string) => string): string {
  const lines = ['# Docs', ''];
  const walk = (current: string): void => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (/\.mdx?$/.test(entry.name)) {
        const { data, body } = parseFrontmatter(readText(full), full);
        const first = headings(body.split('\n')).find((h) => h.level === 1);
        const title = typeof data['title'] === 'string' ? data['title'] : (first?.text ?? entry.name.replace(/\.mdx?$/, ''));
        const description = typeof data['description'] === 'string' ? `: ${data['description']}` : '';
        lines.push(`- [${title}](${display(full)})${description}`);
      }
    }
  };
  walk(dir);
  return `${lines.join('\n')}\n`;
}

const isRepoAdded = (pkg: ResolvedPackage): boolean => pkg.layer === 'added' && (pkg.scope === 'local' || pkg.entry === true);
export const isUserLevel = (pkg: ResolvedPackage): boolean => pkg.layer === 'added' && pkg.scope === 'user' && !pkg.entry;

/**
 * Paths that outputs show: stable package paths for dependencies, project-relative paths inside the
 * project, absolute paths elsewhere. Generated docs indexes are added to `generated`.
 */
export function pathTools(res: Resolution, generatedRoot: (pkg: ResolvedPackage) => string, generated: Map<string, string>) {
  const projectDir = res.projectDir;
  const show = (abs: string): string => (abs.startsWith(projectDir + path.sep) ? relPosix(projectDir, abs) : abs);
  const display = (file: string): string => {
    let best: ResolvedPackage | undefined;
    for (const pkg of res.packages) {
      if (pkg.layer !== 'dependencies') continue;
      if ((file === pkg.dir || file.startsWith(pkg.dir + path.sep)) && (!best || pkg.dir.length > best.dir.length)) best = pkg;
    }
    if (best) return relPosix(projectDir, path.join(projectDir, STATE_DIR, 'pkgs', best.name, path.relative(best.dir, file)));
    return show(file);
  };
  const generatedRule = (rule: FinalRule): string => path.join(generatedRoot(rule.pkg), 'rules', rule.pkg.plugin, `${rule.name}.md`);
  const paths: PathFor = {
    rule: (rule) => (rule.patches.length > 0 ? show(generatedRule(rule)) : display(rule.source)),
    docsIndex: (pkg) => {
      const docs = res.docs.find((d) => d.pkg === pkg);
      if (!docs) return undefined;
      const llms = path.join(docs.dir, 'llms.txt');
      if (isFile(llms)) return display(llms);
      const file = path.join(generatedRoot(pkg), 'docs', pkg.plugin, 'llms.txt');
      generated.set(file, docsIndexText(docs.dir, display));
      return show(file);
    },
  };
  return { show, display, generatedRule, paths };
}

/** The changes that added harnesses make to the repository's rules (spec 4.3, note 4). */
function changesSection(team: Resolution, full: Resolution, rulePath: (rule: FinalRule) => string): string | undefined {
  const added = new Set(full.packages.filter((p) => p.layer === 'added').map((p) => p.name));
  const lines: string[] = [];
  const texts: string[] = [];
  for (const rule of team.rules) {
    const changed = full.rules.find((r) => r.id === rule.id);
    if (!changed) {
      const by = full.excludedUnits.find((u) => u.id === rule.id)?.by;
      if (by !== undefined && added.has(by)) lines.push(`- Ignore the rule ${rule.id} in AGENTS.md: ${by} turns it off on this machine.`);
      continue;
    }
    if (changed.text === rule.text) continue;
    const by = [changed.replacedBy?.by, ...changed.patches.map((p) => p.by)].filter((b): b is string => b !== undefined && added.has(b));
    const who = [...new Set(by)].join(', ');
    if (changed.activation === 'always') texts.push(alwaysOnText(changed, `${rule.id}, changed by ${who}; use this text instead of the one in AGENTS.md`));
    else lines.push(`- Instead of the rule ${rule.id} in AGENTS.md, read ${rulePath(changed)} (changed by ${who})`);
  }
  if (lines.length === 0 && texts.length === 0) return undefined;
  return ["## Changes to this repository's rules", ...texts, ...(lines.length > 0 ? [lines.join('\n')] : [])].join('\n\n');
}

/**
 * `team` is the dependency and project layers alone, for committed outputs. `full` adds the added
 * harnesses, for per-machine outputs. Without `team`, only the outputs of added harnesses change.
 */
export function computePlan(team: Resolution | undefined, full: Resolution): Plan {
  const projectDir = full.projectDir;
  const warnings: string[] = [];
  const generated = new Map<string, string>();
  const links = new Map<string, string>();
  const teamExcludes = new Set<string>([`/${STATE_DIR.split(path.sep).join('/')}/`]);
  const addedExcludes = new Set<string>();
  const teamGen = path.join(projectDir, STATE_DIR);
  const addedGen = path.join(harnesspmHome(), 'generated', repoSlug(projectDir));
  const tools = pathTools(full, (pkg) => (pkg.layer === 'added' ? addedGen : teamGen), generated);

  if (team) for (const pkg of full.packages) if (pkg.layer === 'dependencies') links.set(path.join(projectDir, STATE_DIR, 'pkgs', pkg.name), pkg.dir);

  const stable = (file: string): string => path.resolve(projectDir, tools.display(file));
  const seenRoots = new Set<string>();
  const roots = [path.join(projectDir, '.claude', 'skills'), path.join(projectDir, '.agents', 'skills')].filter((root) => {
    const real = isDir(root) ? realpath(root) : root;
    if (seenRoots.has(real)) return false;
    seenRoots.add(real);
    return true;
  });
  const addLink = (linkPath: string, target: string, into: Set<string>): void => {
    if (exists(linkPath) && !isSymlink(linkPath)) {
      warnings.push(`${relPosix(projectDir, linkPath)} exists and is not a harnesspm link; left as it is`);
      return;
    }
    links.set(linkPath, target);
    into.add(`/${relPosix(projectDir, linkPath)}`);
  };

  for (const skill of full.skills) {
    if (isUserLevel(skill.pkg)) continue;
    const added = skill.pkg.layer === 'added';
    if (!added && !team) continue;
    for (const root of roots) addLink(path.join(root, skill.name), added ? skill.dir : stable(skill.dir), added ? addedExcludes : teamExcludes);
  }

  // Generated rule files: patched rules that agents read from a file, with this machine's text.
  for (const rule of full.rules) {
    if (rule.activation === 'always' || isUserLevel(rule.pkg)) continue;
    if (rule.pkg.layer !== 'added' && !team) continue;
    const teamPatched = (team?.rules.find((r) => r.id === rule.id)?.patches.length ?? 0) > 0;
    if (rule.patches.length > 0 || teamPatched) generated.set(tools.generatedRule(rule), rule.text);
  }

  // File-scoped team rules also get a native Claude Code rule (spec 4.3, note 3).
  if (team) {
    for (const rule of full.rules.filter((r) => r.activation === 'file' && r.pkg.layer !== 'added')) {
      const changed = rule.text !== readText(rule.original);
      const target = changed ? tools.generatedRule(rule) : stable(rule.source);
      if (changed) generated.set(target, rule.text);
      addLink(path.join(projectDir, '.claude', 'rules', 'harnesspm', rule.pkg.plugin, `${rule.name}.md`), target, teamExcludes);
    }
  }

  let committed: Plan['committed'];
  let lock: Lock | undefined = readLock(projectDir);
  if (team) {
    const previous = lock;
    lock = buildLock(team, previous);
    warnings.push(...patchDrift(previous, lock));
    const teamGenerated = new Map<string, string>();
    const teamLock = lock;
    const teamTools = pathTools(team, () => teamGen, teamGenerated);
    const prefix = (pkg: ResolvedPackage): string | undefined => (trustOf(pkg, team, teamLock).trusted ? NPX_LOCAL : undefined);
    // The root block holds what the root reaches and what every workspace shares (spec 3.6, 4.5).
    const keys = team.workspaces.map((ws) => ws.key);
    const shared = (pkg: ResolvedPackage): boolean => pkg.members.has('') || (keys.length > 0 && keys.every((k) => pkg.members.has(k)));
    const rootContent = renderSections(sectionsFor(team, team.packages.filter(shared), teamTools.paths, prefix), teamTools.paths);
    const block = wrapBlock(rootContent !== '' ? rootContent : 'No harness units yet.');
    const workspaces: NonNullable<Plan['committed']>['workspaces'] = [];
    for (const ws of team.workspaces) {
      // Paths in a workspace's block are relative to its folder.
      const toWs = (p: string): string => (path.isAbsolute(p) ? p : relPosix(ws.dir, path.join(projectDir, p)));
      const wsPaths: PathFor = {
        rule: (rule) => toWs(teamTools.paths.rule(rule)),
        docsIndex: (pkg) => {
          const index = teamTools.paths.docsIndex(pkg);
          return index === undefined ? undefined : toWs(index);
        },
      };
      const content = renderSections(sectionsFor(team, team.packages.filter((p) => !shared(p) && p.members.has(ws.key)), wsPaths, prefix), wsPaths);
      const agentsFile = path.join(ws.dir, 'AGENTS.md');
      const existing = readTextIfExists(agentsFile);
      const agentsMd = content !== '' ? upsertBlock(existing, wrapBlock(content)) : extractBlock(existing) !== undefined ? removeBlock(existing) : existing;
      const claudeFile = path.join(ws.dir, 'CLAUDE.md');
      const claudeMd = content !== '' ? withClaudeImport(readTextIfExists(claudeFile)) : readTextIfExists(claudeFile);
      workspaces.push({ dir: ws.dir, agentsMd, claudeMd });
    }
    for (const [file, content] of teamGenerated) if (!generated.has(file)) generated.set(file, content);
    committed = {
      agentsMd: upsertBlock(readTextIfExists(path.join(projectDir, 'AGENTS.md')), block),
      claudeMd: withClaudeImport(readTextIfExists(path.join(projectDir, 'CLAUDE.md'))),
      lock: serializeLock(lock),
      workspaces,
    };
  }

  // Added harnesses with local scope, and every harness's entry for this repository (spec 4.3).
  let content = renderSections(sectionsFor(full, full.packages.filter(isRepoAdded), tools.paths, () => NPX_ANY), tools.paths);
  const changes = team ? changesSection(team, full, (rule) => tools.paths.rule(rule)) : undefined;
  if (changes !== undefined) content = content !== '' ? `${content}\n\n${changes}` : changes;

  const localFile = path.join(projectDir, 'CLAUDE.local.md');
  let localMd: string | undefined;
  if (content !== '' && isTracked(projectDir, 'CLAUDE.local.md')) {
    warnings.push('CLAUDE.local.md is tracked by git, so harnesspm does not write added harnesses into it');
    localMd = readTextIfExists(localFile);
  } else if (content !== '') {
    // CLAUDE.local.md counts as a CLAUDE.md: without one, Claude Code would stop reading AGENTS.md (spec 4.3, note 1).
    const needsImport = !isFile(path.join(projectDir, 'CLAUDE.md')) && isFile(path.join(projectDir, 'AGENTS.md'));
    localMd = upsertBlock(readTextIfExists(localFile), wrapBlock(content));
    if (needsImport && !hasClaudeImport(localMd)) localMd = `@AGENTS.md\n\n${localMd}`;
    addedExcludes.add('/CLAUDE.local.md');
  } else {
    // Remove only harnesspm's own block. A file without one stays as it is.
    const existing = readTextIfExists(localFile);
    localMd = extractBlock(existing) === undefined ? existing : removeBlock(existing, /^\s*(@AGENTS\.md)?\s*$/);
  }

  // Codex files are per machine unless the repository commits its own .codex/ (spec 4.3, note 2).
  const codexFile = path.join(projectDir, '.codex', 'config.toml');
  const codexTracked = ['.codex/config.toml', '.codex/hooks.json', '.codex/rules'].some((rel) => isTracked(projectDir, rel));
  const codexOurs = !codexTracked && (readTextIfExists(codexFile) ?? CODEX_MARKER).startsWith(CODEX_MARKER);
  if (!codexOurs) warnings.push('.codex/ belongs to the repository, so harnesspm writes nothing there and Codex misses some units. See `harnesspm status`.');
  const claudeOurs = !isTracked(projectDir, '.claude/settings.local.json');
  if (!claudeOurs) warnings.push('.claude/settings.local.json is tracked by git, so harnesspm writes no hooks or permissions there');

  // Executable units and sub-agents (spec 4.3, chapter 5), with trust (spec 6.2).
  const trust = (pkg: ResolvedPackage) => trustOf(pkg, full, lock);
  const agentDirs = { claudeAgents: path.join(projectDir, '.claude', 'agents'), codexAgents: path.join(projectDir, '.codex', 'agents') };
  const teamExec = team ? desiredEntries(full, new Set(full.packages.filter((p) => p.layer !== 'added')), trust, { ...agentDirs, npx: () => NPX_LOCAL }) : undefined;
  const addedExec = desiredEntries(full, new Set(full.packages.filter(isRepoAdded)), trust, { ...agentDirs, npx: () => NPX_ANY });
  warnings.push(...(teamExec?.warnings ?? []), ...addedExec.warnings);

  return {
    ...(committed ? { committed } : {}),
    generated,
    generatedRoots: [...(team ? [path.join(teamGen, 'rules'), path.join(teamGen, 'docs')] : []), addedGen],
    links,
    ...(team ? { teamExcludes: [...teamExcludes].sort() } : {}),
    addedExcludes: [...addedExcludes].sort(),
    localMd,
    codexInstructions: content,
    codexOurs,
    claudeOurs,
    exec: { ...(teamExec ? { team: teamExec } : {}), added: addedExec },
    warnings,
  };
}

function sectionRange(lines: string[], marks: readonly [string, string]): [number, number] | undefined {
  const start = lines.indexOf(marks[0]);
  if (start < 0) return undefined;
  const end = lines.indexOf(marks[1], start);
  return end < 0 ? undefined : [start, end];
}

function readSection(text: string | undefined, marks: readonly [string, string]): string[] {
  const lines = (text ?? '').split('\n');
  const range = sectionRange(lines, marks);
  return range ? lines.slice(range[0] + 1, range[1]).filter((l) => l.startsWith('/')) : [];
}

function writeSection(text: string | undefined, marks: readonly [string, string], entries: string[]): string {
  const lines = (text ?? '').split('\n');
  const range = sectionRange(lines, marks);
  const section = entries.length > 0 ? [marks[0], ...entries, marks[1]] : [];
  if (range) lines.splice(range[0], range[1] - range[0] + 1, ...section);
  else if (section.length > 0) {
    while (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
    if (lines.length > 0) lines.push('');
    lines.push(...section);
  }
  while (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
  return lines.length > 0 ? `${lines.join('\n')}\n` : '';
}

function unlinkAndPrune(target: string, stopAt: string): void {
  fs.unlinkSync(target);
  for (let dir = path.dirname(target); dir.startsWith(stopAt + path.sep); dir = path.dirname(dir)) {
    try {
      fs.rmdirSync(dir);
    } catch {
      break;
    }
  }
}

export function repoStateFile(projectDir: string): string {
  const result = spawnSync('git', ['rev-parse', '--git-path', 'harnesspm/state.json'], { cwd: projectDir, encoding: 'utf8' });
  const p = result.status === 0 ? result.stdout.trim() : path.join('.git', 'harnesspm', 'state.json');
  return path.isAbsolute(p) ? p : path.join(projectDir, p);
}

export function repoTargets(projectDir: string, plan: Pick<Plan, 'claudeOurs' | 'codexOurs'>): Targets {
  return {
    claudeSettings: path.join(projectDir, '.claude', 'settings.local.json'),
    claudeJson: claudeJsonFile(),
    claudeProject: projectDir,
    codexHooks: path.join(projectDir, '.codex', 'hooks.json'),
    codexRules: path.join(projectDir, '.codex', 'rules', 'harnesspm.rules'),
    stateFile: repoStateFile(projectDir),
    writeClaude: plan.claudeOurs,
    writeCodex: plan.codexOurs,
  };
}

export interface ApplyResult {
  changed: string[];
  /** Entries a model run could not add (spec 6.2, rule 4). */
  held: string[];
}

/** Writes the plan. Returns the project-relative paths that changed and the entries held back. */
export function applyPlan(projectDir: string, plan: Plan): ApplyResult {
  const changed: string[] = [];
  const held: string[] = [];
  const note = (file: string, did: boolean): void => {
    if (did) changed.push(relPosix(projectDir, file));
  };

  for (const root of plan.generatedRoots) fs.rmSync(root, { recursive: true, force: true });
  for (const [file, content] of plan.generated) writeIfChanged(file, content);
  for (const [linkPath, target] of plan.links) note(linkPath, linkIfChanged(linkPath, target));

  // Executable entries in shared files, before the excludes so that every written file is listed.
  const widen = caller() !== 'model';
  const targets = repoTargets(projectDir, plan);
  const teamExcludes = plan.teamExcludes ? [...plan.teamExcludes] : undefined;
  const addedExcludes = [...plan.addedExcludes];
  let codexMcp: Record<string, Record<string, unknown>> = {};
  for (const [group, entries, into] of [['team', plan.exec.team, teamExcludes], ['added', plan.exec.added, addedExcludes]] as const) {
    if (!entries) continue;
    const applied = applyEntries(group, entries, targets, widen);
    for (const file of applied.changed) changed.push(file.startsWith(projectDir + path.sep) ? relPosix(projectDir, file) : file);
    held.push(...applied.held);
    codexMcp = applied.codexMcp;
    for (const file of applied.files) if (file.startsWith(projectDir + path.sep)) into?.push(`/${relPosix(projectDir, file)}`);
  }

  // .codex/config.toml: developer_instructions and MCP servers.
  const codexFile = path.join(projectDir, '.codex', 'config.toml');
  if (plan.codexOurs) {
    const parts = [
      ...(plan.codexInstructions !== '' ? [`developer_instructions = ${tomlString(plan.codexInstructions)}`] : []),
      ...(Object.keys(codexMcp).length > 0 ? [tomlTables('mcp_servers', codexMcp)] : []),
    ];
    if (parts.length > 0) {
      note(codexFile, writeIfChanged(codexFile, `${CODEX_MARKER}\n${parts.join('\n\n')}\n`));
      addedExcludes.push('/.codex/config.toml');
    } else if (isFile(codexFile)) {
      fs.rmSync(codexFile);
      changed.push('.codex/config.toml');
    }
  }
  for (const dir of [path.join(projectDir, '.codex', 'rules'), path.join(projectDir, '.codex', 'agents'), path.join(projectDir, '.codex'), path.join(projectDir, '.claude', 'agents')]) {
    try {
      fs.rmdirSync(dir);
    } catch {
      // Not empty, or not there.
    }
  }

  const excludeFile = gitExcludeFile(projectDir);
  if (excludeFile) {
    const before = readTextIfExists(excludeFile);
    const prevTeam = readSection(before, TEAM_SECTION);
    const prevAdded = readSection(before, ADDED_SECTION);
    const keep = new Set([...(teamExcludes ?? prevTeam), ...addedExcludes]);
    // Remove links from the last sync that this sync no longer writes.
    for (const entry of new Set([...prevTeam, ...prevAdded])) {
      const target = path.join(projectDir, entry);
      if (keep.has(entry) || !isSymlink(target)) continue;
      unlinkAndPrune(target, projectDir);
      changed.push(entry.slice(1));
    }
    let text = before;
    const sorted = (list: string[]): string[] => [...new Set(list)].sort();
    if (teamExcludes) text = writeSection(text, TEAM_SECTION, sorted(teamExcludes));
    text = writeSection(text, ADDED_SECTION, sorted(addedExcludes));
    ensureDir(path.dirname(excludeFile));
    writeIfChanged(excludeFile, text);
  }

  if (plan.committed) {
    note(path.join(projectDir, 'AGENTS.md'), writeIfChanged(path.join(projectDir, 'AGENTS.md'), plan.committed.agentsMd));
    note(path.join(projectDir, 'CLAUDE.md'), writeIfChanged(path.join(projectDir, 'CLAUDE.md'), plan.committed.claudeMd));
    note(path.join(projectDir, LOCK_FILE), writeIfChanged(path.join(projectDir, LOCK_FILE), plan.committed.lock));
    for (const ws of plan.committed.workspaces) {
      const agentsFile = path.join(ws.dir, 'AGENTS.md');
      if (ws.agentsMd !== undefined) note(agentsFile, writeIfChanged(agentsFile, ws.agentsMd));
      else if (isFile(agentsFile)) {
        fs.rmSync(agentsFile);
        changed.push(relPosix(projectDir, agentsFile));
      }
      if (ws.claudeMd !== undefined) note(path.join(ws.dir, 'CLAUDE.md'), writeIfChanged(path.join(ws.dir, 'CLAUDE.md'), ws.claudeMd));
    }
  }

  const localFile = path.join(projectDir, 'CLAUDE.local.md');
  if (plan.localMd !== undefined) note(localFile, writeIfChanged(localFile, plan.localMd));
  else if (isFile(localFile)) {
    fs.rmSync(localFile);
    changed.push('CLAUDE.local.md');
  }
  return { changed, held };
}

/** Compares the committed outputs with the plan (spec 6.4). Returns the differences. */
export function checkPlan(projectDir: string, plan: Plan): string[] {
  if (!plan.committed) return ['the dependencies are not installed, so the committed outputs cannot be checked'];
  const problems: string[] = [];
  const agents = readTextIfExists(path.join(projectDir, 'AGENTS.md'));
  if (extractBlock(agents) !== extractBlock(plan.committed.agentsMd)) problems.push('AGENTS.md: the harnesspm block is out of date');
  if (!hasClaudeImport(readTextIfExists(path.join(projectDir, 'CLAUDE.md')))) problems.push('CLAUDE.md: the @AGENTS.md line is missing');
  if (readTextIfExists(path.join(projectDir, LOCK_FILE)) !== plan.committed.lock) problems.push(`${LOCK_FILE} is out of date`);
  for (const ws of plan.committed.workspaces) {
    const rel = relPosix(projectDir, path.join(ws.dir, 'AGENTS.md'));
    if (extractBlock(readTextIfExists(path.join(ws.dir, 'AGENTS.md'))) !== extractBlock(ws.agentsMd)) problems.push(`${rel}: the harnesspm block is out of date`);
  }
  const lock = JSON.parse(plan.committed.lock) as { packages: Record<string, { version: string; approved?: string }> };
  for (const [name, entry] of Object.entries(lock.packages)) {
    if (entry.approved !== undefined && entry.approved !== entry.version) {
      problems.push(`${name} ${entry.version} is pinned and not approved (approved: ${entry.approved}). Run \`npx harnesspm approve ${name}\`.`);
    }
  }
  return problems;
}
