// Managed blocks (spec 4.6): AGENTS.md for the team, CLAUDE.local.md and user-level files for added harnesses.
import { demoteHeadings, headings } from './sections.ts';
import type { FinalRule, Resolution, ResolvedPackage } from './resolve.ts';

export const BLOCK_BEGIN = '<!-- BEGIN:harnesspm — generated by `harnesspm sync`. Do not edit. To change a rule, run `npx harnesspm why <ID>`. -->';
export const BLOCK_END = '<!-- END:harnesspm -->';
const BEGIN_PREFIX = '<!-- BEGIN:harnesspm';

/** Paths that outputs use for a rule file and a docs index. */
export interface PathFor {
  rule(rule: FinalRule): string;
  docsIndex(pkg: ResolvedPackage): string | undefined;
}

export interface Section {
  heading: string;
  rules: FinalRule[];
  docsIndex?: { path: string; id: string };
  /** Lines before the rules, such as a note on what the section changes. */
  intro?: string[];
  /** Script lines: scripts the agent may run, with their command. */
  scripts?: string[];
}

function withoutTitle(body: string): string {
  const lines = body.split('\n');
  const first = headings(lines)[0];
  if (first && first.level === 1) lines.splice(first.line, 1);
  return lines.join('\n').trim();
}

export function packageHeading(pkg: ResolvedPackage): string {
  if (pkg.layer === 'project') return `## ${pkg.name} (this project)`;
  if (pkg.layer === 'added') {
    const spec = pkg.added?.source.spec ?? pkg.name;
    if (pkg.entry) return `## ${pkg.plugin}: entry for this repository (${spec})`;
    return `## ${pkg.plugin} (${spec}, ${pkg.scope} scope)`;
  }
  return `## ${pkg.name} ${pkg.version}${pkg.via !== undefined ? ` (via ${pkg.via})` : ''}`;
}

export function alwaysOnText(rule: FinalRule, label = rule.id): string {
  const body = demoteHeadings(withoutTitle(rule.body), 2);
  return `### ${rule.title} (${label})${body !== '' ? `\n\n${body}` : ''}`;
}

export function pointerLine(rule: FinalRule, file: string): string {
  if (rule.activation === 'file') {
    const globs = (rule.paths ?? []).map((p) => `\`${p}\``).join(', ');
    const description = rule.description !== undefined ? ` — ${rule.description}` : '';
    return `- When editing ${globs}, read ${file}${description} (${rule.id})`;
  }
  return `- ${rule.description}: read ${file} (${rule.id})`;
}

export function renderSections(sections: Section[], paths: PathFor): string {
  const out: string[] = [];
  for (const section of sections) {
    const parts = [section.heading, ...(section.intro ?? [])];
    for (const rule of section.rules.filter((r) => r.activation === 'always')) parts.push(alwaysOnText(rule));
    const pointers = section.rules.filter((r) => r.activation !== 'always').map((r) => pointerLine(r, paths.rule(r)));
    if (section.docsIndex) pointers.push(`- Docs: ${section.docsIndex.path} (${section.docsIndex.id})`);
    pointers.push(...(section.scripts ?? []));
    if (pointers.length > 0) parts.push(pointers.join('\n'));
    if (parts.length > 1) out.push(parts.join('\n\n'));
  }
  return out.join('\n\n');
}

/** `runPrefix` returns the command prefix for a trusted package's scripts, or undefined to list none. */
export function sectionsFor(res: Resolution, packages: ResolvedPackage[], paths: PathFor, runPrefix: (pkg: ResolvedPackage) => string | undefined = () => undefined): Section[] {
  return packages.map((pkg) => {
    const index = paths.docsIndex(pkg);
    const prefix = runPrefix(pkg);
    const scripts =
      prefix === undefined
        ? []
        : res.scripts.filter((s) => s.pkg === pkg && s.description !== undefined).map((s) => `- Script: \`${prefix} run ${pkg.plugin}:${s.name}\` — ${s.description} (${s.id})`);
    return {
      heading: packageHeading(pkg),
      rules: res.rules.filter((r) => r.pkg === pkg),
      ...(index !== undefined ? { docsIndex: { path: index, id: `${pkg.plugin}:docs` } } : {}),
      ...(scripts.length > 0 ? { scripts } : {}),
    };
  });
}

export function wrapBlock(content: string): string {
  return `${BLOCK_BEGIN}\n${content}\n${BLOCK_END}`;
}

/** The committed block: the dependency and project layers. */
export function renderBlock(res: Resolution, paths: PathFor, runPrefix?: (pkg: ResolvedPackage) => string | undefined): string {
  const content = renderSections(sectionsFor(res, res.packages, paths, runPrefix), paths);
  return wrapBlock(content !== '' ? content : 'No harness units yet.');
}

/** Puts the block into a Markdown file. Text outside the block never changes. */
export function upsertBlock(existing: string | undefined, block: string): string {
  if (existing === undefined || existing.trim() === '') return `${block}\n`;
  const start = existing.indexOf(BEGIN_PREFIX);
  const end = existing.indexOf(BLOCK_END, start);
  if (start >= 0 && end > start) return existing.slice(0, start) + block + existing.slice(end + BLOCK_END.length);
  return `${existing.replace(/\s+$/, '')}\n\n${block}\n`;
}

/** Removes the block. Returns undefined when nothing else is left in the file. */
export function removeBlock(existing: string | undefined, leftover: RegExp = /^\s*$/): string | undefined {
  if (existing === undefined) return undefined;
  const start = existing.indexOf(BEGIN_PREFIX);
  const end = existing.indexOf(BLOCK_END, start);
  const rest = start >= 0 && end > start ? existing.slice(0, start).replace(/\s+$/, '') + existing.slice(end + BLOCK_END.length) : existing;
  if (leftover.test(rest)) return undefined;
  return `${rest.replace(/\s+$/, '')}\n`;
}

export function extractBlock(text: string | undefined): string | undefined {
  if (text === undefined) return undefined;
  const start = text.indexOf(BEGIN_PREFIX);
  const end = text.indexOf(BLOCK_END, start);
  return start >= 0 && end > start ? text.slice(start, end + BLOCK_END.length) : undefined;
}

export const CLAUDE_IMPORT = '@AGENTS.md';

export function hasClaudeImport(text: string | undefined): boolean {
  return text !== undefined && /^@AGENTS\.md[ \t]*$/m.test(text);
}

export function withClaudeImport(existing: string | undefined): string {
  if (existing === undefined || existing.trim() === '') return `${CLAUDE_IMPORT}\n`;
  if (hasClaudeImport(existing)) return existing;
  return `${CLAUDE_IMPORT}\n\n${existing}`;
}

/** TOML basic multi-line string. */
export function tomlString(text: string): string {
  return `"""\n${text.replace(/\\/g, '\\\\').replace(/"""/g, '""\\"')}\n"""`;
}
