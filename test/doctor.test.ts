test('doctor: in a project below the git root, entries an older harnesspm wrote from the wrong folder ask for a sync', () => {
  const repo = project({}, {}, false);
  const dir = path.join(repo, 'docs-site');
  writeFiles(dir, { 'package.json': JSON.stringify({ name: 'site', version: '1.0.0', devDependencies: { '@acme/kit': '1' } }), 'harnesspm.json': '{}\n' });
  installPackage(dir, '@acme/kit', { plugin: 'kit', harness: { 'dev.harnesspm/rules/forms.md': '# Forms\n\nUse the Form component.\n' } });
  assert.equal(run(dir, 'sync').status, 0);
  // What 0.9 wrote: the root's section, with paths from the project's folder.
  const exclude = path.join(repo, '.git/info/exclude');
  fs.writeFileSync(exclude, '# BEGIN harnesspm (generated by `harnesspm sync`; per-machine outputs)\n/node_modules/.harnesspm/\n# END harnesspm\n');
  const result = run(dir, 'doctor');
  assert.equal(result.status, 1);
  assert.match(result.stdout, /❌ node_modules\/\.harnesspm is not ignored by git, so `git add` can pick it up\. Run `npx harnesspm sync`, which lists it in \.git\/info\/exclude\./);
  assert.doesNotMatch(result.stdout, /brings it back/);
  assert.equal(run(dir, 'sync').status, 0);
  assert.equal(run(dir, 'doctor').status, 0);
});

